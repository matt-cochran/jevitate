#!/usr/bin/env node
// Computes this build's identity — {commit, builtAt} — for issue #83 ("no build identity in
// results"): the dev workflow (`npm link` to a live working tree) means the CLI's
// package.json version alone doesn't change between rebuilds, so results from two different
// builds in the same session were indistinguishable.
//
// Two build paths ship `dist/bin.js` and BOTH need real (never fabricated) build identity:
//   - `pnpm --filter @jevitate/cli run bundle` (esbuild, build.mjs) — gets commit/builtAt
//     folded in as literals via an esbuild `define`, computed here and passed in by build.mjs.
//   - `pnpm --filter @jevitate/cli run build` (`tsc --build`, what a dev `npm link` install
//     runs — AGENTS.md) — has no bundler substitution, so it needs a real module to compile.
//     This script writes that module, `src/build-info.generated.ts`, as a "build" pre-step.
//
// Regenerated on every build; gitignored, same convention as `packages/cli/skills` (see the
// comment in build.mjs and the matching .gitignore entry).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, "..", "src", "build-info.generated.ts");

/** The commit this build was made from, short SHA — or `"unknown"`. NEVER fabricated: a
 *  missing `.git` (an extracted tarball), a shallow clone without HEAD, or `git` being
 *  unavailable all fall back to the same honest `"unknown"`, never a guessed value. */
export function currentCommit() {
  try {
    const sha = execFileSync("git", ["rev-parse", "--short", "HEAD"], {
      cwd: here,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    return sha.length > 0 ? sha : "unknown";
  } catch {
    return "unknown";
  }
}

/** Computes {commit, builtAt} and writes the generated module `tsc --build` compiles. */
export function writeBuildInfoModule() {
  const commit = currentCommit();
  const builtAt = new Date().toISOString();
  const src = `// AUTO-GENERATED by packages/cli/scripts/generate-build-info.mjs at build time.
// Do not edit by hand — regenerated on every \`build\`/\`bundle\` run. Gitignored.
//
// The tsc-build counterpart to build.mjs's esbuild \`define\`: a dev \`npm link\` install runs
// this plain \`tsc --build\` dist (no bundler substitution), so it needs real committed values
// here instead. See ./engine.ts, which prefers the esbuild-injected value when present and
// falls back to these.
export const GENERATED_COMMIT: string = ${JSON.stringify(commit)};
export const GENERATED_BUILT_AT: string = ${JSON.stringify(builtAt)};
`;
  writeFileSync(outFile, src, "utf8");
  return { commit, builtAt };
}

// Run directly, e.g. as the package.json "build" pre-step: `node scripts/generate-build-info.mjs`.
if (import.meta.url === `file://${process.argv[1]}`) {
  const { commit, builtAt } = writeBuildInfoModule();
  console.log(`generated build-info -> ${outFile} (commit ${commit}, builtAt ${builtAt})`);
}
